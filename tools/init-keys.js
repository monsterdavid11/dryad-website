import { generateKeyPairSync, createPublicKey, createHash } from "node:crypto";
import { mkdirSync, existsSync, writeFileSync, readFileSync } from "node:fs";
import { resolve } from "node:path";
const dir = resolve("data/keys");
mkdirSync(dir, { recursive: true });
const release = process.argv.includes("--release");
const path = resolve(dir, release ? "release-1.0.0.pem" : "license.pem");
if (!existsSync(path)) {
  const { privateKey } = generateKeyPairSync("rsa", { modulusLength: 3072 });
  writeFileSync(path, privateKey.export({ type: "pkcs8", format: "pem" }), {
    mode: 0o600,
  });
}
const pub = createPublicKey(readFileSync(path));
writeFileSync(
  resolve(dir, release ? "release-1.0.0-public.pem" : "license-public.pem"),
  pub.export({ type: "spki", format: "pem" }),
);
const jwk = pub.export({ format: "jwk" }),
  n = Buffer.from(jwk.n, "base64url"),
  e = Buffer.from(jwk.e, "base64url");
const header = Buffer.alloc(24);
header.writeUInt32LE(0x31415352, 0);
header.writeUInt32LE(n.length * 8, 4);
header.writeUInt32LE(e.length, 8);
header.writeUInt32LE(n.length, 12);
const blob = Buffer.concat([header, e, n]),
  kid = createHash("sha256")
    .update(pub.export({ type: "spki", format: "der" }))
    .digest("hex")
    .slice(0, 16);
writeFileSync(
  resolve(
    release ? "../src/dryad_release_public_key.h" : "../src/dryad_public_key.h",
  ),
  `// Public key only. Generated by web/tools/init-keys.js. Never embed a private key.\n#pragma once\nnamespace dryad { inline constexpr char KeyId[]="${kid}"; inline constexpr unsigned char PublicKey[]={${[...blob].join(",")}}; }\n`,
);
mkdirSync(resolve("../launcher"), { recursive: true });
writeFileSync(
  resolve(
    release
      ? "../launcher/release-license-public.pem"
      : "../launcher/license-public.pem",
  ),
  pub.export({ type: "spki", format: "pem" }),
);
console.log(
  "Dryad signing key initialized. Public key pinned in the launcher and native build. Private key remains in ignored data/keys/.",
);
